    PRIMARY KEY (id),
    UNIQUE KEY uq_emergency_alert_number (alert_number),
    KEY idx_emergency_owner_status (property_id, status, created_at),
    KEY idx_emergency_tenant (tenant_id, created_at),
    CONSTRAINT fk_emergency_tenant FOREIGN KEY (tenant_id) REFERENCES users (id),
    CONSTRAINT fk_emergency_lease FOREIGN KEY (lease_id) REFERENCES leases (id),
