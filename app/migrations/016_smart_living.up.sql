CREATE TABLE shared_facilities (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    owner_id BIGINT UNSIGNED NOT NULL,
    property_id BIGINT UNSIGNED NOT NULL,
    name VARCHAR(150) NOT NULL,
    location VARCHAR(190) NOT NULL,
    description TEXT NULL,
    opens_at TIME NOT NULL,
    closes_at TIME NOT NULL,
    slot_minutes SMALLINT UNSIGNED NOT NULL DEFAULT 60,
    capacity SMALLINT UNSIGNED NOT NULL DEFAULT 1,
    requires_approval TINYINT(1) NOT NULL DEFAULT 1,
    status ENUM('active','inactive') NOT NULL DEFAULT 'active',
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    PRIMARY KEY (id),
    UNIQUE KEY uq_shared_facility_property_name (property_id, name),
    KEY idx_shared_facility_owner_status (owner_id, status),
    CONSTRAINT fk_shared_facility_owner FOREIGN KEY (owner_id) REFERENCES users (id),
    CONSTRAINT fk_shared_facility_property FOREIGN KEY (property_id) REFERENCES properties (id),
    CONSTRAINT chk_shared_facility_slot CHECK (slot_minutes BETWEEN 15 AND 240),
    CONSTRAINT chk_shared_facility_capacity CHECK (capacity BETWEEN 1 AND 100)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;

CREATE TABLE facility_reservations (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    reservation_number VARCHAR(50) NOT NULL,
    facility_id BIGINT UNSIGNED NOT NULL,
    tenant_id BIGINT UNSIGNED NOT NULL,
    lease_id BIGINT UNSIGNED NOT NULL,
    property_id BIGINT UNSIGNED NOT NULL,
    room_id BIGINT UNSIGNED NOT NULL,
    reservation_date DATE NOT NULL,
    starts_at TIME NOT NULL,
    ends_at TIME NOT NULL,
    purpose VARCHAR(500) NULL,
    status ENUM('pending','approved','rejected','cancelled','completed') NOT NULL DEFAULT 'pending',
    owner_note VARCHAR(1000) NULL,
    reviewed_by BIGINT UNSIGNED NULL,
    reviewed_at DATETIME(6) NULL,
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    PRIMARY KEY (id),
    UNIQUE KEY uq_facility_reservation_number (reservation_number),
    KEY idx_facility_reservation_schedule (facility_id, reservation_date, status, starts_at, ends_at),
    KEY idx_facility_reservation_tenant (tenant_id, created_at),
    CONSTRAINT fk_facility_reservation_facility FOREIGN KEY (facility_id) REFERENCES shared_facilities (id),
    CONSTRAINT fk_facility_reservation_tenant FOREIGN KEY (tenant_id) REFERENCES users (id),
    CONSTRAINT fk_facility_reservation_lease FOREIGN KEY (lease_id) REFERENCES leases (id),
    CONSTRAINT fk_facility_reservation_property FOREIGN KEY (property_id) REFERENCES properties (id),
    CONSTRAINT fk_facility_reservation_room FOREIGN KEY (room_id) REFERENCES rooms (id),
    CONSTRAINT fk_facility_reservation_reviewer FOREIGN KEY (reviewed_by) REFERENCES users (id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;

