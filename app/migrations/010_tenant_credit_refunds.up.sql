CREATE TABLE tenant_credit_refunds (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    refund_number VARCHAR(50) NOT NULL,
    owner_id BIGINT UNSIGNED NOT NULL,
    tenant_id BIGINT UNSIGNED NOT NULL,
    property_id BIGINT UNSIGNED NOT NULL,
    tenant_credit_id BIGINT UNSIGNED NOT NULL,
    bank_account_id BIGINT UNSIGNED NOT NULL,
    amount BIGINT UNSIGNED NOT NULL,
    refund_date DATE NOT NULL,
    reason TEXT NOT NULL,
    proof_storage_path VARCHAR(500) NOT NULL,
    status ENUM('posted','reversed') NOT NULL DEFAULT 'posted',
    created_by BIGINT UNSIGNED NOT NULL,
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    PRIMARY KEY (id),
    UNIQUE KEY uq_tenant_credit_refund_number (refund_number),
    UNIQUE KEY uq_tenant_credit_refund_credit (tenant_credit_id),
    KEY idx_tenant_credit_refund_tenant (tenant_id, refund_date),
    CONSTRAINT chk_tenant_credit_refund_amount CHECK (amount > 0),
    CONSTRAINT fk_tenant_credit_refund_owner FOREIGN KEY (owner_id) REFERENCES users (id),
    CONSTRAINT fk_tenant_credit_refund_tenant FOREIGN KEY (tenant_id) REFERENCES users (id),
    CONSTRAINT fk_tenant_credit_refund_property FOREIGN KEY (property_id) REFERENCES properties (id),
    CONSTRAINT fk_tenant_credit_refund_credit FOREIGN KEY (tenant_credit_id) REFERENCES tenant_credits (id),
    CONSTRAINT fk_tenant_credit_refund_bank FOREIGN KEY (bank_account_id) REFERENCES bank_accounts (id),
    CONSTRAINT fk_tenant_credit_refund_actor FOREIGN KEY (created_by) REFERENCES users (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;
