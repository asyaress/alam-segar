CREATE TABLE digital_documents (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    owner_id BIGINT UNSIGNED NOT NULL,
    property_id BIGINT UNSIGNED NOT NULL,
    tenant_id BIGINT UNSIGNED NOT NULL,
    document_type ENUM('invoice','receipt','lease','inspection') NOT NULL,
    source_id BIGINT UNSIGNED NOT NULL,
    document_number VARCHAR(50) NOT NULL,
    version_number INT UNSIGNED NOT NULL DEFAULT 1,
    title VARCHAR(255) NOT NULL,
    snapshot_json LONGTEXT NOT NULL,
    snapshot_sha256 CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    verification_code CHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    status ENUM('issued','owner_signed','awaiting_tenant','completed','void') NOT NULL DEFAULT 'issued',
    issued_by BIGINT UNSIGNED NOT NULL,
    issued_at DATETIME(6) NOT NULL,
    owner_signed_by BIGINT UNSIGNED NULL,
    owner_signed_at DATETIME(6) NULL,
    owner_signature_sha256 CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
    tenant_signed_by BIGINT UNSIGNED NULL,
    tenant_signed_at DATETIME(6) NULL,
    tenant_signature_sha256 CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
    voided_by BIGINT UNSIGNED NULL,
    voided_at DATETIME(6) NULL,
    void_reason VARCHAR(1000) NULL,
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    PRIMARY KEY (id),
    UNIQUE KEY uq_digital_document_number (document_number),
    UNIQUE KEY uq_digital_document_verification (verification_code),
    UNIQUE KEY uq_digital_document_source_version (document_type, source_id, version_number),
    KEY idx_digital_document_owner (owner_id, status, issued_at),
    KEY idx_digital_document_tenant (tenant_id, status, issued_at),
    CONSTRAINT fk_digital_document_owner FOREIGN KEY (owner_id) REFERENCES users (id),
    CONSTRAINT fk_digital_document_property FOREIGN KEY (property_id) REFERENCES properties (id),
    CONSTRAINT fk_digital_document_tenant FOREIGN KEY (tenant_id) REFERENCES users (id),
    CONSTRAINT fk_digital_document_issuer FOREIGN KEY (issued_by) REFERENCES users (id),
    CONSTRAINT fk_digital_document_owner_signer FOREIGN KEY (owner_signed_by) REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT fk_digital_document_tenant_signer FOREIGN KEY (tenant_signed_by) REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT fk_digital_document_voider FOREIGN KEY (voided_by) REFERENCES users (id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;
