CREATE TABLE lease_terminations (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    termination_number VARCHAR(50) NOT NULL,
    lease_id BIGINT UNSIGNED NOT NULL,
    owner_id BIGINT UNSIGNED NOT NULL,
    tenant_id BIGINT UNSIGNED NOT NULL,
    property_id BIGINT UNSIGNED NOT NULL,
    effective_date DATE NOT NULL,
    settlement_decision ENUM('refund','retain') NOT NULL,
    cancelled_unpaid_amount BIGINT UNSIGNED NOT NULL DEFAULT 0,
    settled_paid_amount BIGINT UNSIGNED NOT NULL DEFAULT 0,
    bank_account_id BIGINT UNSIGNED NULL,
    proof_storage_path VARCHAR(500) NULL,
    reason TEXT NOT NULL,
    created_by BIGINT UNSIGNED NOT NULL,
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    PRIMARY KEY (id),
    UNIQUE KEY uq_lease_termination_number (termination_number),
    UNIQUE KEY uq_lease_termination_lease (lease_id),
    KEY idx_lease_termination_tenant (tenant_id, effective_date),
    CONSTRAINT fk_lease_termination_lease FOREIGN KEY (lease_id) REFERENCES leases (id),
    CONSTRAINT fk_lease_termination_owner FOREIGN KEY (owner_id) REFERENCES users (id),
    CONSTRAINT fk_lease_termination_tenant FOREIGN KEY (tenant_id) REFERENCES users (id),
    CONSTRAINT fk_lease_termination_property FOREIGN KEY (property_id) REFERENCES properties (id),
    CONSTRAINT fk_lease_termination_bank FOREIGN KEY (bank_account_id) REFERENCES bank_accounts (id),
    CONSTRAINT fk_lease_termination_actor FOREIGN KEY (created_by) REFERENCES users (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;
